#pragma once

#include <NvInferRuntime.h>

#include <string>
#include <vector>

namespace trt_edgellm::plugins
{

//! Dense linear with FP8 (E4M3) weights and FP16 activations: y[T, N] = scale[n] * sum_k x[T, k] * w[n, k].
//!
//! Inputs: x [T, K] (FP16), weight [N, K / 4] (INT32 words holding four E4M3 bytes), scale [N] (FP16 or FP32, one per output row). Output: y [T, N] (FP16).
//! Decode steps of at most four tokens run a warp-per-row GEMV at memory bandwidth, longer inputs a tensor-core GEMM that dequantises the weights tile by tile.
class Fp8LinearPlugin : public nvinfer1::IPluginV3,
                        public nvinfer1::IPluginV3OneCore,
                        public nvinfer1::IPluginV3OneBuild,
                        public nvinfer1::IPluginV3OneRuntime
{
public:
    Fp8LinearPlugin(std::string const& name, int32_t outFeatures, int32_t inFeatures, int32_t weightFormat = 0);

    nvinfer1::IPluginCapability* getCapabilityInterface(nvinfer1::PluginCapabilityType type) noexcept override;
    nvinfer1::IPluginV3* clone() noexcept override;

    char const* getPluginName() const noexcept override;
    char const* getPluginVersion() const noexcept override;
    char const* getPluginNamespace() const noexcept override;
    void setPluginNamespace(char const* pluginNamespace) noexcept;

    int32_t getNbOutputs() const noexcept override;
    int32_t getOutputDataTypes(nvinfer1::DataType* outputTypes, int32_t nbOutputs, nvinfer1::DataType const* inputTypes,
        int32_t nbInputs) const noexcept override;
    int32_t getOutputShapes(nvinfer1::DimsExprs const* inputs, int32_t nbInputs, nvinfer1::DimsExprs const* shapeInputs,
        int32_t nbShapeInputs, nvinfer1::DimsExprs* outputs, int32_t nbOutputs,
        nvinfer1::IExprBuilder& exprBuilder) noexcept override;
    bool supportsFormatCombination(int32_t pos, nvinfer1::DynamicPluginTensorDesc const* inOut, int32_t nbInputs,
        int32_t nbOutputs) noexcept override;
    int32_t configurePlugin(nvinfer1::DynamicPluginTensorDesc const* in, int32_t nbInputs,
        nvinfer1::DynamicPluginTensorDesc const* out, int32_t nbOutputs) noexcept override;
    size_t getWorkspaceSize(nvinfer1::DynamicPluginTensorDesc const* inputs, int32_t nbInputs,
        nvinfer1::DynamicPluginTensorDesc const* outputs, int32_t nbOutputs) const noexcept override;
    int32_t enqueue(nvinfer1::PluginTensorDesc const* inputDesc, nvinfer1::PluginTensorDesc const* outputDesc,
        void const* const* inputs, void* const* outputs, void* workspace, cudaStream_t stream) noexcept override;
    int32_t onShapeChange(nvinfer1::PluginTensorDesc const* in, int32_t nbInputs, nvinfer1::PluginTensorDesc const* out,
        int32_t nbOutputs) noexcept override;
    nvinfer1::IPluginV3* attachToContext(nvinfer1::IPluginResourceContext* context) noexcept override;
    nvinfer1::PluginFieldCollection const* getFieldsToSerialize() noexcept override;

private:
    std::string mLayerName;
    std::string mNamespace;
    int32_t mOutFeatures;
    int32_t mInFeatures;
    int32_t mWeightFormat{0}; //!< 0 = E4M3 weights, 1 = INT8 weights (per-row scale in both cases)
    std::vector<nvinfer1::PluginField> mData;
    nvinfer1::PluginFieldCollection mFields{};
};

class Fp8LinearPluginCreator : public nvinfer1::IPluginCreatorV3One
{
public:
    Fp8LinearPluginCreator();

    char const* getPluginName() const noexcept override;
    char const* getPluginVersion() const noexcept override;
    nvinfer1::PluginFieldCollection const* getFieldNames() noexcept override;
    char const* getPluginNamespace() const noexcept override;
    void setPluginNamespace(char const* pluginNamespace) noexcept;
    nvinfer1::IPluginV3* createPlugin(
        char const* name, nvinfer1::PluginFieldCollection const* fc, nvinfer1::TensorRTPhase phase) noexcept override;

private:
    static std::vector<nvinfer1::PluginField> mAttributes;
    nvinfer1::PluginFieldCollection mFields{};
    std::string mNamespace;
};

} // namespace trt_edgellm::plugins
