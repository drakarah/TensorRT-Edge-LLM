"""Generates cpuMissFixtureFp4.inc: one NVFP4 expert matrix packed by the exporter's Marlin packer (repack_nvfp4_a16_marlin_linear), one activation vector and the
float64 result of the dense computation  y[n] = sum_k x[k] * e2m1(code[n, k]) * e4m3(scale[n, k / 16]) * weight_scale_2.
usage (repo root): python unittests/cpp/plugins/int4MoePlugin/genCpuMissFp4Fixture.py > unittests/cpp/plugins/int4MoePlugin/cpuMissFixtureFp4.inc"""
import numpy as np, torch
from tensorrt_edgellm.checkpoint.repacking import repack_nvfp4_a16_marlin_linear

K, N = 256, 128
g = torch.Generator().manual_seed(7)
codes = torch.randint(0, 16, (N, K), generator=g, dtype=torch.uint8)
packed = (codes[:, 0::2] | (codes[:, 1::2] << 4)).contiguous()
# E4M3 scale bytes in a range that keeps the products moderate (exponent field 5..9, any mantissa)
scale_bytes = (torch.randint(5, 10, (N, K // 16), generator=g) << 3 | torch.randint(0, 8, (N, K // 16), generator=g)).to(torch.uint8)
mult = 0.0123
qweights, block_scales, global_scale, _, _ = repack_nvfp4_a16_marlin_linear(packed, scale_bytes.view(torch.float8_e4m3fn), torch.tensor(mult))
levels = np.array([0.0, 0.5, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0])
value = levels[(codes & 7).numpy()] * np.where((codes & 8).numpy() != 0, -1.0, 1.0)
scales = scale_bytes.view(torch.float8_e4m3fn).float().numpy().astype(np.float64)
dense = value * np.repeat(scales, 16, axis=1) * mult
x = np.random.RandomState(3).uniform(-1, 1, K).astype(np.float32)
y = dense @ x.astype(np.float64)
w32 = qweights.contiguous().to(torch.int8).view(torch.int32).numpy().reshape(-1)
sb = block_scales.contiguous().to(torch.int8).view(torch.uint8).numpy().reshape(-1)
def arr(name, ctype, a, fmt):
    body = ",\n    ".join(", ".join(fmt(v) for v in a[i:i + 8]) for i in range(0, len(a), 8))
    return f"constexpr {ctype} {name}[{len(a)}] = {{\n    {body}}};\n"
print("// Generated by genCpuMissFp4Fixture.py with tensorrt_edgellm.checkpoint.repacking.repack_nvfp4_a16_marlin_linear (K = 256, N = 128, one expert): int32 words of the packed")
print("// codes, E4M3 scale bytes in the Marlin layout, the global multiplier as stored (multiplier * 2^7, fp16 bits), the activations and the float64 dense result.")
print("#pragma once\n#include <cstdint>\n\nnamespace cpuMissFixtureFp4\n{")
print(f"constexpr int32_t kK = {K};\nconstexpr int32_t kN = {N};\nconstexpr double kMult = {mult!r};")
print(f"constexpr uint16_t kGlobalBits = {int(global_scale.view(torch.int16).item()) & 0xFFFF};")
print(arr("kWeights", "int32_t", w32, lambda v: str(int(v))), end="")
print(arr("kScales", "uint8_t", sb, lambda v: str(int(v))), end="")
print(arr("kX", "float", x, lambda v: repr(float(v)) + "F"), end="")
print(arr("kY", "double", y, lambda v: repr(float(v))), end="")
print("} // namespace cpuMissFixtureFp4")
